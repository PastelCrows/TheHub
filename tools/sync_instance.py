"""Copy the AUTHORED parts of the hub instance into the repo, so they are under version control.

The problem: the work that cannot be re-downloaded lives inside Prism's instance folder, not in
this project. 197 quest files, 12 structure .nbt files, the KubeJS scripts and the generated
dimension JSONs, and the pocket*.json configs that drive PocketQuests - none of it had any
history, and the FTB Quests lang migration has already eaten 280 quests' text once.

What is tracked, and why it is only ~5 MB:

  kubejs/                 11 server scripts + 77 generated dimension/worldgen JSONs + structures
  datapacks/hub_worldgen/ the worldgen datapack, including 5 more structures
  config/pocket*.json     the seven configs that drive PocketQuests
  config/ftbquests/       the merged book - 83 chapters, 699 quests
  defaultconfigs/
  options.txt             the tuned client settings
  instance.cfg            the JVM args and heap, which took measurement to get right

What is NOT, and must not be: mods/ (869 MB, 251 jars, all re-downloadable from Modrinth),
resourcepacks/ and shaderpacks/ (603 MB of third-party zips - and redistributing them would be
someone else's licence to worry about), saves/, logs/, crash-reports/, and the .prehubfix
backups my own tools leave behind.

horror-desaturated IS tracked despite living in resourcepacks/, because it is generated by
tools/build_desaturated_pack.py from vanilla and is therefore ours.

Run this before committing. It mirrors - files deleted in the instance get deleted in the repo -
so the repo is a true reflection rather than an append-only pile.
"""
import filecmp
import os
import shutil
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
INST = os.path.expandvars(r"%APPDATA%\PrismLauncher\instances\The Hub")
MC = os.path.join(INST, "minecraft")
DEST = os.path.join(REPO, "instance")

# (source relative to the instance, destination relative to instance/ in the repo)
TREES = [
    (os.path.join("minecraft", "kubejs"), "kubejs"),
    (os.path.join("minecraft", "datapacks", "hub_worldgen"), "datapacks/hub_worldgen"),
    (os.path.join("minecraft", "config", "ftbquests"), "config/ftbquests"),
    (os.path.join("minecraft", "defaultconfigs"), "defaultconfigs"),
    (os.path.join("minecraft", "resourcepacks", "horror-desaturated"),
     "resourcepacks/horror-desaturated"),
]
GLOBS = [
    (os.path.join("minecraft", "config"), "pocket", ".json", "config"),
]
FILES = [
    (os.path.join("minecraft", "options.txt"), "options.txt"),
    ("instance.cfg", "instance.cfg"),
    (os.path.join("minecraft", "config", "modernfix-mixins.properties"),
     "config/modernfix-mixins.properties"),
    (os.path.join("minecraft", "config", "dimswap.json"), "config/dimswap.json"),
    # Lost Cities decides whether hub:lostcities is a city or an ordinary forest, and the
    # setting that does it lived only in the instance until it was found to be in the WRONG
    # FILE entirely (config/lostcities-common.toml, which the mod stopped reading). Tracked
    # now so the live path is the one under review.
    (os.path.join("minecraft", "config", "lostcities", "common.toml"),
     "config/lostcities/common.toml"),
    (os.path.join("minecraft", "config", "lostcities-server.toml"),
     "config/lostcities-server.toml"),
]
# The brand: rendered assets and the FancyMenu layout that places them. Both are OURS -
# generated by build_brand_assets.py and build_menu_layouts.py - so unlike resourcepacks/
# and shaderpacks/ there is no licence reason to leave them out, and a pack whose title
# screen lives only on one machine is not shareable.
TREES += [
    (os.path.join("minecraft", "config", "fancymenu"), "config/fancymenu"),
    (os.path.join("minecraft", "config", "simplesplashscreen"), "config/simplesplashscreen"),
]
SKIP_SUFFIX = (".prehubfix", ".prehubtune", ".part")


def ignore(_dir, names):
    return [n for n in names if n.endswith(SKIP_SUFFIX)]


def sync_tree(src, dst):
    added = changed = removed = 0
    if not os.path.isdir(src):
        return None
    for root, _dirs, files in os.walk(src):
        rel = os.path.relpath(root, src)
        target_dir = os.path.join(dst, rel) if rel != "." else dst
        os.makedirs(target_dir, exist_ok=True)
        for f in files:
            if f.endswith(SKIP_SUFFIX):
                continue
            s = os.path.join(root, f)
            d = os.path.join(target_dir, f)
            if not os.path.exists(d):
                shutil.copy2(s, d)
                added += 1
            elif not filecmp.cmp(s, d, shallow=False):
                shutil.copy2(s, d)
                changed += 1
    # mirror deletions
    for root, _dirs, files in os.walk(dst):
        rel = os.path.relpath(root, dst)
        back = os.path.join(src, rel) if rel != "." else src
        for f in files:
            if not os.path.exists(os.path.join(back, f)):
                os.remove(os.path.join(root, f))
                removed += 1
    return added, changed, removed


def main():
    os.makedirs(DEST, exist_ok=True)
    total = [0, 0, 0]
    print("SYNCING authored instance files -> %s\n" % DEST)

    for src_rel, dst_rel in TREES:
        src = os.path.join(INST, src_rel)
        dst = os.path.join(DEST, dst_rel.replace("/", os.sep))
        r = sync_tree(src, dst)
        if r is None:
            print("   %-34s MISSING in the instance" % dst_rel)
            continue
        total = [a + b for a, b in zip(total, r)]
        n = sum(1 for _r, _d, fs in os.walk(dst) for _f in fs)
        print("   %-34s %4d files   (+%d ~%d -%d)" % (dst_rel, n, r[0], r[1], r[2]))

    for src_dir, prefix, suffix, dst_rel in GLOBS:
        src = os.path.join(INST, src_dir)
        dst = os.path.join(DEST, dst_rel)
        os.makedirs(dst, exist_ok=True)
        n = 0
        for f in sorted(os.listdir(src)):
            if f.startswith(prefix) and f.endswith(suffix):
                shutil.copy2(os.path.join(src, f), os.path.join(dst, f))
                n += 1
        print("   %-34s %4d files   (%s*%s)" % (dst_rel, n, prefix, suffix))

    for src_rel, dst_rel in FILES:
        src = os.path.join(INST, src_rel)
        dst = os.path.join(DEST, dst_rel.replace("/", os.sep))
        if not os.path.exists(src):
            print("   %-34s MISSING" % dst_rel)
            continue
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src, dst)
        print("   %-34s    1 file" % dst_rel)

    # ---------------------------------------------------------------- verify
    print("\nVERIFY")
    files = 0
    size = 0
    for root, _d, fs in os.walk(DEST):
        for f in fs:
            files += 1
            size += os.path.getsize(os.path.join(root, f))
    print("   %-40s %d" % ("files tracked", files))
    print("   %-40s %.1f MB" % ("total size", size / 1048576.0))

    ok = True
    # the things that must be there
    for must, label in (
            (os.path.join(DEST, "config", "ftbquests", "quests", "chapters"), "quest chapters"),
            (os.path.join(DEST, "kubejs", "server_scripts"), "kubejs scripts"),
            (os.path.join(DEST, "config", "pocketquests.json"), "pocketquests.json"),
            (os.path.join(DEST, "config", "pocketdifficulty.json"), "pocketdifficulty.json"),
            (os.path.join(DEST, "instance.cfg"), "instance.cfg (JVM args)")):
        there = os.path.exists(must)
        print("   %-40s %s" % (label, "OK" if there else "MISSING"))
        ok = ok and there

    chapters = len(os.listdir(os.path.join(DEST, "config", "ftbquests", "quests", "chapters"))) \
        if os.path.isdir(os.path.join(DEST, "config", "ftbquests", "quests", "chapters")) else 0
    print("   %-40s %d" % ("chapter files", chapters))
    nbt = sum(1 for r, _d, fs in os.walk(DEST) for f in fs if f.endswith(".nbt"))
    print("   %-40s %d" % ("structure .nbt files", nbt))

    # the things that must NOT be there
    for never in ("mods", "saves", "logs", "shaderpacks"):
        bad = os.path.exists(os.path.join(DEST, never))
        print("   %-40s %s" % ("%s/ NOT tracked" % never, "OK" if not bad else "LEAKED"))
        ok = ok and not bad
    leftover = [f for r, _d, fs in os.walk(DEST) for f in fs if f.endswith(SKIP_SUFFIX)]
    print("   %-40s %s" % ("no .prehubfix/.part files", "OK" if not leftover else leftover[:3]))
    ok = ok and not leftover

    print("\n   %s" % ("ALL CHECKS PASSED" if ok else "PROBLEMS FOUND"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
