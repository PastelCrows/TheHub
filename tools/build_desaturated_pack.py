# -*- coding: utf-8 -*-
"""Extend the horror-desaturated resource pack: amethyst, and the foliage/grass colormaps.

The pack was originally generated by an ad hoc script that was not kept, so this one starts by
RECOVERING the transform: it samples textures that were transformed, pairs each pixel with its
vanilla original, and fits the saturation / brightness / contrast constants by grid search. New
textures then go through the recovered transform rather than a fresh guess, so nothing looks
subtly different from the pack already in use.

Two fixes, two different causes - the measurement is the whole point here:

LEAVES. Not a texture problem at all. Vanilla oak_leaves.png has a mean saturation of 0.017 and
spruce_leaves.png is exactly 0.000 - leaf textures are near-greyscale MASKS by design, and every
bit of their green comes from the biome foliage tint in assets/minecraft/textures/colormap/
foliage.png, which the pack never overrode. Desaturating the textures (which the original script
did do) could never have worked. So this writes desaturated colormaps instead.

The colormaps get saturation reduction ONLY, no darkening. The tint is MULTIPLIED onto a texture
that has already been darkened by the transform, so darkening the tint as well would make leaves
noticeably darker than everything else rather than equally grey. grass.png gets the same
treatment even though it was not asked for: grass, vines and sugar cane share the mechanism, and
leaving grass green next to grey leaves would look like a bug.

AMETHYST. Measured at 0.499 vanilla and 0.499 in the pack - skipped, exactly like glowstone
(0.557 unchanged). The original script preserved light sources, and amethyst clusters and buds
emit light, so they were excluded by that rule. Overriding it for the amethyst family only, on
request; other light sources keep their colour.

Idempotent: a texture already at the target saturation is left alone, so re-running is safe.
"""
import io
import os
import sys
import zipfile

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

try:
    from PIL import Image
except ImportError:
    print("Pillow is required: python -m pip install Pillow")
    raise SystemExit(1)

MC = os.path.expandvars(r"%APPDATA%\PrismLauncher\instances\The Hub\minecraft")
PACK = os.path.join(MC, "resourcepacks", "horror-desaturated")
CLIENT = os.path.expandvars(
    r"%APPDATA%\PrismLauncher\libraries\com\mojang\minecraft\1.21.1\minecraft-1.21.1-client.jar")
TEX = "assets/minecraft/textures/"

# textures the original transform definitely touched, used to recover its constants
FIT_SAMPLES = [
    "block/oak_planks.png", "block/bricks.png", "block/sand.png", "block/gravel.png",
    "block/red_wool.png", "block/blue_wool.png", "block/pumpkin_side.png",
    "block/spruce_planks.png", "block/terracotta.png", "block/copper_block.png",
]

# the amethyst family: textures to bring in line despite being light sources
AMETHYST = [
    "block/amethyst_block.png", "block/budding_amethyst.png", "block/amethyst_cluster.png",
    "block/large_amethyst_bud.png", "block/medium_amethyst_bud.png",
    "block/small_amethyst_bud.png", "block/calibrated_sculk_sensor_amethyst.png",
    "item/amethyst_shard.png",
]

COLORMAPS = ["colormap/foliage.png", "colormap/grass.png"]


# ----------------------------------------------------------------- transform
def transform_pixel(r, g, b, sat_k, bright, contrast):
    mx, mn = max(r, g, b), min(r, g, b)
    lum = 0.299 * r + 0.587 * g + 0.114 * b
    # desaturate toward luminance
    r = lum + (r - lum) * sat_k
    g = lum + (g - lum) * sat_k
    b = lum + (b - lum) * sat_k
    out = []
    for c in (r, g, b):
        c = (c - 128.0) * contrast + 128.0      # contrast about mid grey
        c *= bright                              # then darken
        out.append(int(max(0, min(255, round(c)))))
    return tuple(out)


def apply_transform(img, sat_k, bright, contrast):
    img = img.convert("RGBA")
    px = list(img.getdata())
    img.putdata([transform_pixel(r, g, b, sat_k, bright, contrast) + (a,)
                 for r, g, b, a in px])
    return img


def desaturate_only(img, sat_k):
    img = img.convert("RGBA")
    out = []
    for r, g, b, a in img.getdata():
        lum = 0.299 * r + 0.587 * g + 0.114 * b
        out.append((int(round(lum + (r - lum) * sat_k)),
                    int(round(lum + (g - lum) * sat_k)),
                    int(round(lum + (b - lum) * sat_k)), a))
    img.putdata(out)
    return img


def mean_sat(img):
    img = img.convert("RGBA")
    tot, n = 0.0, 0
    for r, g, b, a in img.getdata():
        if a < 16:
            continue
        mx, mn = max(r, g, b), min(r, g, b)
        tot += 0.0 if mx == 0 else (mx - mn) / float(mx)
        n += 1
    return tot / n if n else 0.0


# ----------------------------------------------------------------- recover constants
def recover(z):
    """Grid search the three constants against real vanilla->pack pixel pairs."""
    pairs = []
    used = []
    for name in FIT_SAMPLES:
        p = os.path.join(PACK, "assets", "minecraft", "textures", name.replace("/", os.sep))
        if not os.path.exists(name) and not os.path.exists(p):
            continue
        try:
            van = Image.open(io.BytesIO(z.read(TEX + name))).convert("RGBA")
        except KeyError:
            continue
        if not os.path.exists(p):
            continue
        pack = Image.open(p).convert("RGBA")
        if van.size != pack.size:
            continue
        vd, pd = list(van.getdata()), list(pack.getdata())
        for (vr, vg, vb, va), (pr, pg, pb, _pa) in zip(vd, pd):
            if va < 16:
                continue
            pairs.append((vr, vg, vb, pr, pg, pb))
        used.append(name)
    if not pairs:
        return None, [], 0.0

    # coarse then fine grid, plain least squares on RGB
    best = (None, 1e18)
    grid = [(s / 20.0, b / 20.0, c / 20.0)
            for s in range(0, 21, 1) for b in range(10, 25, 1) for c in range(16, 29, 1)]
    for sat_k, bright, contrast in grid:
        err = 0.0
        for vr, vg, vb, pr, pg, pb in pairs[::7]:        # stride for speed
            tr, tg, tb = transform_pixel(vr, vg, vb, sat_k, bright, contrast)
            err += (tr - pr) ** 2 + (tg - pg) ** 2 + (tb - pb) ** 2
        if err < best[1]:
            best = ((sat_k, bright, contrast), err)
    params, err = best
    n = len(pairs[::7]) * 3
    rmse = (err / n) ** 0.5 if n else 0.0
    return params, used, rmse


# ----------------------------------------------------------------- main
def main():
    if not os.path.isdir(PACK):
        print("pack not found: %s" % PACK)
        return 1
    z = zipfile.ZipFile(CLIENT)

    print("RECOVERING the original transform from the pack itself")
    params, used, rmse = recover(z)
    if params is None:
        print("   could not fit; aborting rather than guessing")
        return 1
    sat_k, bright, contrast = params
    print("   fitted on %d textures: %s" % (len(used), ", ".join(n.split("/")[-1] for n in used)))
    print("   saturation x%.2f   brightness x%.2f   contrast x%.2f   (RMSE %.1f / 255)"
          % (sat_k, bright, contrast, rmse))
    if rmse > 24:
        print("   WARNING: poor fit, the original transform was probably not this shape")

    changed = []

    print("\nAMETHYST  (light-source rule overridden on request)")
    for name in AMETHYST:
        try:
            van = Image.open(io.BytesIO(z.read(TEX + name))).convert("RGBA")
        except KeyError:
            print("   %-44s not in client jar, skipped" % name)
            continue
        dest = os.path.join(PACK, "assets", "minecraft", "textures", name.replace("/", os.sep))
        before = mean_sat(Image.open(dest)) if os.path.exists(dest) else mean_sat(van)
        out = apply_transform(van, sat_k, bright, contrast)
        after = mean_sat(out)
        if os.path.exists(dest) and abs(before - after) < 0.01:
            print("   %-44s already done (%.3f)" % (name, before))
            continue
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        out.save(dest)
        changed.append(name)
        print("   %-44s %.3f -> %.3f" % (name, before, after))

    print("\nCOLORMAPS  (saturation only - the tint multiplies an already darkened texture)")
    for name in COLORMAPS:
        try:
            van = Image.open(io.BytesIO(z.read(TEX + name))).convert("RGBA")
        except KeyError:
            print("   %-44s not in client jar, skipped" % name)
            continue
        dest = os.path.join(PACK, "assets", "minecraft", "textures", name.replace("/", os.sep))
        out = desaturate_only(van, sat_k)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        out.save(dest)
        changed.append(name)
        print("   %-44s %.3f -> %.3f" % (name, mean_sat(van), mean_sat(out)))

    # ----------------------------------------------------------------- verify
    print("\nVERIFY")
    ok = True
    for name in AMETHYST[:4] + COLORMAPS:
        dest = os.path.join(PACK, "assets", "minecraft", "textures", name.replace("/", os.sep))
        if not os.path.exists(dest):
            print("   MISSING  %s" % name)
            ok = False
            continue
        try:
            van_s = mean_sat(Image.open(io.BytesIO(z.read(TEX + name))))
        except KeyError:
            continue
        pk_s = mean_sat(Image.open(dest))
        drop = 0.0 if van_s == 0 else 1 - pk_s / van_s
        good = drop > 0.4
        print("   %-44s vanilla %.3f -> %.3f  (%.0f%% less saturated) %s"
              % (name, van_s, pk_s, drop * 100, "OK" if good else "NOT DESATURATED"))
        ok = ok and good

    # a light source that is NOT amethyst must still be untouched
    gl = os.path.join(PACK, "assets", "minecraft", "textures", "block", "glowstone.png")
    gl_s = mean_sat(Image.open(gl))
    gl_v = mean_sat(Image.open(io.BytesIO(z.read(TEX + "block/glowstone.png"))))
    kept = abs(gl_s - gl_v) < 0.01
    print("   %-44s %.3f (vanilla %.3f) %s"
          % ("glowstone still coloured", gl_s, gl_v, "OK" if kept else "CHANGED - rule broken"))
    ok = ok and kept

    # the pack must still be a valid pack
    meta = os.path.join(PACK, "pack.mcmeta")
    print("   %-44s %s" % ("pack.mcmeta present", os.path.exists(meta)))
    ok = ok and os.path.exists(meta)

    z.close()
    print("\n   %d textures written. %s" % (len(changed), "ALL CHECKS PASSED" if ok
                                            else "PROBLEMS FOUND"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
